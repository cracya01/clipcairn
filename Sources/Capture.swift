import AppKit
import ImageIO
import LinkPresentation
import UniformTypeIdentifiers
import Vision

/// Watches the general pasteboard and records every copy.
@MainActor
final class ClipboardWatcher {
    private let store: ClipStore
    private let settings = AppSettings.shared
    private var timer: Timer?
    private var lastChange = NSPasteboard.general.changeCount
    /// changeCount of our own last write, which must not be recorded again.
    private var ownChange = -1

    /// Called after a new entry was stored.
    var onNewEntry: ((ClipEntry) -> Void)?

    /// Password managers mark secrets with these types (nspasteboard.org convention).
    private static let skipMarkers: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]
    /// Written by Clipcairn itself when pasting; such copies are not recorded again.
    static let ownMarker = "com.cracya01.clipcairn"
    /// Set by macOS on content from another device via Universal Clipboard.
    static let remoteMarker = "com.apple.is-remote-clipboard"
    /// Safari/WebKit page archives (can be tens of MB) are not stored; the other formats are.
    private static let notStored: Set<String> = ["com.apple.webarchive", "Apple Web Archive pasteboard type"]

    init(store: ClipStore) { self.store = store }

    func start() {
        guard timer == nil else { return }
        lastChange = NSPasteboard.general.changeCount
        let t = Timer(timeInterval: 0.25, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        RunLoop.main.add(t, forMode: .common)
        timer = t
        startPasteMonitor()
    }

    /// Marks the current pasteboard content as written by us.
    func markOwnWrite() {
        ownChange = NSPasteboard.general.changeCount
        lastChange = ownChange
    }

    /// changeCount of a Universal Clipboard item waiting to be pasted before it is saved.
    private var pendingRemote: Int?
    private var forceRemote = false
    private var keyMonitor: Any?

    /// Watches for ⌘V in other apps, to save a pending Universal Clipboard item once it is pasted.
    /// Candidate mechanism, to be confirmed with real iPhone copies (global key monitoring needs
    /// Accessibility access, which Clipcairn already asks for to paste).
    private func startPasteMonitor() {
        guard keyMonitor == nil else { return }
        // Installing a global key monitor without Accessibility access makes macOS show its
        // permission prompt; wait until access is granted instead.
        guard AXIsProcessTrusted() else {
            DispatchQueue.main.asyncAfter(deadline: .now() + 5) { [weak self] in self?.startPasteMonitor() }
            return
        }
        keyMonitor = NSEvent.addGlobalMonitorForEvents(matching: .keyDown) { [weak self] e in
            guard e.modifierFlags.intersection(.deviceIndependentFlagsMask) == .command,
                  e.charactersIgnoringModifiers?.lowercased() == "v" else { return }
            MainActor.assumeIsolated { self?.pastedPendingRemote() }
        }
    }

    private func pastedPendingRemote() {
        guard let p = pendingRemote, p == NSPasteboard.general.changeCount else { return }
        // Give the target app a moment to fetch the content from the other device.
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.5) { [weak self] in
            guard let self, self.pendingRemote == p else { return }
            self.forceRemote = true
            self.lastChange = -1
            self.poll()
            self.forceRemote = false
        }
    }

    private func poll() {
        let pb = NSPasteboard.general
        let cc = pb.changeCount
        guard cc != lastChange else { return }
        lastChange = cc
        guard cc != ownChange, settings.recording else { return }

        let front = NSWorkspace.shared.frontmostApplication
        if let bid = front?.bundleIdentifier, settings.disabledApps.contains(where: { $0.bundleID == bid }) { return }
        // Copies from the Passwords menu bar extra happen while another app is frontmost.
        // Raycast checks for it too (seen in its binary: isPasswordsMenuBarExtraActive).
        if settings.disabledApps.contains(where: { $0.bundleID == "com.apple.Passwords" }),
           Self.passwordsMenuBarExtraActive() { return }

        let allTypes = Set((pb.types ?? []).map(\.rawValue))
        if allTypes.contains(Self.ownMarker) || !allTypes.isDisjoint(with: Self.skipMarkers) { return }
        if allTypes.contains(Self.remoteMarker), !settings.recordUniversalClipboard, !forceRemote {
            // As Raycast by default: save content from another Apple device only once it is pasted
            // on this Mac. Reading it now would fetch it from that device.
            pendingRemote = cc
            return
        }
        pendingRemote = nil

        var items: [ClipItem] = []
        for item in pb.pasteboardItems ?? [] {
            var types: [(String, Data)] = []
            for t in item.types where !t.rawValue.hasPrefix("dyn.") && !Self.notStored.contains(t.rawValue) {
                if let data = item.data(forType: t) { types.append((t.rawValue, data)) }
            }
            if !types.isEmpty { items.append(ClipItem(types: types)) }
        }
        guard !items.isEmpty else { return }

        guard var clip = Classifier.classify(pb: pb, items: items) else { return }
        if allTypes.contains(Self.remoteMarker) {
            clip.sourceBundle = nil
            clip.sourceName = "其他设备"
        } else if let declared = pb.string(forType: NSPasteboard.PasteboardType("org.nspasteboard.source")),
                  !declared.isEmpty,
                  let url = NSWorkspace.shared.urlForApplication(withBundleIdentifier: declared) {
            // The copying app declared itself (nspasteboard.org); more accurate than the frontmost app
            // for background tools. Exclusions still apply to the declared app.
            if settings.disabledApps.contains(where: { $0.bundleID == declared }) { return }
            clip.sourceBundle = declared
            clip.sourceName = FileManager.default.displayName(atPath: url.path)
                .replacingOccurrences(of: ".app", with: "")
        } else {
            clip.sourceBundle = front?.bundleIdentifier
            clip.sourceName = front?.localizedName
        }
        guard let entry = store.add(clip) else { return }
        onNewEntry?(entry)
        enrich(entry, items: items)
    }

    /// True while the Passwords menu bar extra shows its window (needs Accessibility access).
    static func passwordsMenuBarExtraActive() -> Bool {
        guard AXIsProcessTrusted(),
              let app = NSRunningApplication.runningApplications(
                withBundleIdentifier: "com.apple.Passwords.MenuBarExtra").first else { return false }
        let ax = AXUIElementCreateApplication(app.processIdentifier)
        var value: CFTypeRef?
        guard AXUIElementCopyAttributeValue(ax, kAXWindowsAttribute as CFString, &value) == .success,
              let windows = value as? [AXUIElement] else { return false }
        return !windows.isEmpty
    }

    /// Background work after storing: text recognition for images, previews for links.
    func enrich(_ entry: ClipEntry, items: [ClipItem]) {
        let store = self.store
        if entry.kind == .image, settings.ocrEnabled,
           let data = Classifier.imageData(in: items)?.data {
            let accurate = settings.ocrMode == .accurate
            Task.detached(priority: .utility) {
                let text = TextRecognizer.recognize(data, accurate: accurate)
                guard let text, !text.isEmpty else { return }
                await MainActor.run { store.setOCR(entry.id, text) }
            }
        }
        if entry.kind == .link, settings.linkPreviews,
           let s = entry.text, let url = URL(string: s.trimmingCharacters(in: .whitespacesAndNewlines)) {
            LinkVisuals.fetch(url) { icon, preview in
                store.setLinkVisuals(entry.id, icon: icon, preview: preview)
            }
        }
    }
}

// MARK: - Classification

enum Classifier {
    static let formattedTypes: Set<String> = ["public.rtf", "public.html", "com.apple.flat-rtfd", "com.apple.webarchive"]

    static func classify(pb: NSPasteboard, items: [ClipItem]) -> NewClip? {
        // Files
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            let title = urls.count == 1 ? urls[0].lastPathComponent : "\(urls.count) 个文件"
            return NewClip(kind: .file, formatted: false, title: title,
                           text: urls.map(\.path).joined(separator: "\n"),
                           byteSize: totalBytes(items), items: items)
        }
        // Text-like
        if let s = pb.string(forType: .string), !s.isEmpty {
            let types = Set(items.flatMap { $0.types.map(\.type) })
            let kind = textKind(s)
            return NewClip(kind: kind, formatted: kind == .text && !types.isDisjoint(with: formattedTypes),
                           title: title(of: s), text: s, byteSize: s.utf8.count, items: items)
        }
        // Image
        if let img = imageData(in: items) {
            let info = ImageInfo(img.data)
            let title = info.width > 0 ? "图片 (\(info.width)×\(info.height))" : "图片"
            return NewClip(kind: .image, formatted: false, title: title, text: nil,
                           width: info.width, height: info.height, byteSize: img.data.count,
                           thumb: info.thumbnail, items: items)
        }
        return nil
    }

    static func totalBytes(_ items: [ClipItem]) -> Int {
        items.reduce(0) { $0 + $1.types.reduce(0) { $0 + $1.data.count } }
    }

    /// The best image representation: PNG, then other common formats, then TIFF.
    static func imageData(in items: [ClipItem]) -> (type: String, data: Data)? {
        let order = ["public.png", "public.jpeg", "public.heic", "org.webmproject.webp", "com.compuserve.gif",
                     "public.tiff", "com.apple.pict", "com.microsoft.bmp"]
        let all = items.flatMap { $0.types }
        for t in order { if let hit = all.first(where: { $0.type == t }) { return hit } }
        return all.first { UTType($0.type)?.conforms(to: .image) ?? false }
    }

    static func title(of s: String) -> String {
        let line = s.split(whereSeparator: \.isNewline)
            .map { $0.trimmingCharacters(in: .whitespaces) }
            .first { !$0.isEmpty } ?? s.trimmingCharacters(in: .whitespacesAndNewlines)
        return String(line.prefix(300))
    }

    static func textKind(_ s: String) -> ClipKind {
        let t = s.trimmingCharacters(in: .whitespacesAndNewlines)
        if t.isEmpty || t.contains(where: { $0.isWhitespace }) { return .text }
        if ColorParser.parse(t) != nil { return .color }
        if t.range(of: #"^[A-Za-z0-9._%+\-]+@[A-Za-z0-9.\-]+\.[A-Za-z]{2,}$"#, options: .regularExpression) != nil {
            return .email
        }
        if let u = URL(string: t), let scheme = u.scheme?.lowercased() {
            if scheme == "mailto" { return .email }
            if ["http", "https", "ftp"].contains(scheme), u.host != nil { return .link }
        }
        return .text
    }
}

// MARK: - Images

struct ImageInfo {
    var width = 0
    var height = 0
    var thumbnail: Data?

    init(_ data: Data) {
        guard let src = CGImageSourceCreateWithData(data as CFData, nil) else { return }
        if let p = CGImageSourceCopyPropertiesAtIndex(src, 0, nil) as? [CFString: Any] {
            width = p[kCGImagePropertyPixelWidth] as? Int ?? 0
            height = p[kCGImagePropertyPixelHeight] as? Int ?? 0
        }
        let opts: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: 128,
        ]
        if let cg = CGImageSourceCreateThumbnailAtIndex(src, 0, opts as CFDictionary) {
            thumbnail = NSBitmapImageRep(cgImage: cg).representation(using: .png, properties: [:])
        }
    }

    static func cgImage(_ data: Data) -> CGImage? {
        guard let src = CGImageSourceCreateWithData(data as CFData, nil) else { return nil }
        return CGImageSourceCreateImageAtIndex(src, 0, nil)
    }

    static func png(_ data: Data) -> Data? {
        guard let cg = cgImage(data) else { return nil }
        return NSBitmapImageRep(cgImage: cg).representation(using: .png, properties: [:])
    }
}

enum TextRecognizer {
    /// On-device text recognition (Vision). Returns nil when nothing is found.
    nonisolated static func recognize(_ data: Data, accurate: Bool) -> String? {
        guard let cg = ImageInfo.cgImage(data) else { return nil }
        let req = VNRecognizeTextRequest()
        req.recognitionLevel = accurate ? .accurate : .fast
        req.usesLanguageCorrection = accurate
        req.recognitionLanguages = ["zh-Hans", "zh-Hant", "en-US", "ja-JP", "ko-KR"]
        req.automaticallyDetectsLanguage = true
        do {
            try VNImageRequestHandler(cgImage: cg).perform([req])
        } catch {
            return nil
        }
        let lines = (req.results ?? []).compactMap { $0.topCandidates(1).first?.string }
        return lines.isEmpty ? nil : lines.joined(separator: "\n")
    }

    nonisolated static func qrCodes(_ data: Data) -> [String] {
        guard let cg = ImageInfo.cgImage(data) else { return [] }
        let req = VNDetectBarcodesRequest()
        req.symbologies = [.qr]
        try? VNImageRequestHandler(cgImage: cg).perform([req])
        return (req.results ?? []).compactMap { $0.payloadStringValue }
    }
}

// MARK: - Colors

enum ColorParser {
    static func parse(_ s: String) -> NSColor? {
        let t = s.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
        if t.hasPrefix("#") {
            let hex = String(t.dropFirst())
            guard [3, 4, 6, 8].contains(hex.count), let v = UInt64(hex, radix: 16) else { return nil }
            func c(_ x: UInt64, _ bits: UInt64) -> CGFloat { CGFloat(x) / CGFloat((1 << bits) - 1) }
            switch hex.count {
            case 3: return NSColor(srgbRed: c(v >> 8 & 0xF, 4), green: c(v >> 4 & 0xF, 4), blue: c(v & 0xF, 4), alpha: 1)
            case 4: return NSColor(srgbRed: c(v >> 12 & 0xF, 4), green: c(v >> 8 & 0xF, 4), blue: c(v >> 4 & 0xF, 4), alpha: c(v & 0xF, 4))
            case 6: return NSColor(srgbRed: c(v >> 16 & 0xFF, 8), green: c(v >> 8 & 0xFF, 8), blue: c(v & 0xFF, 8), alpha: 1)
            default: return NSColor(srgbRed: c(v >> 24 & 0xFF, 8), green: c(v >> 16 & 0xFF, 8), blue: c(v >> 8 & 0xFF, 8), alpha: c(v & 0xFF, 8))
            }
        }
        // rgb(1,2,3) / rgba(1,2,3,0.5)
        if let m = t.range(of: #"^rgba?\(\s*(\d{1,3})\s*,\s*(\d{1,3})\s*,\s*(\d{1,3})\s*(,\s*(0|1|0?\.\d+)\s*)?\)$"#,
                           options: .regularExpression) {
            let nums = t[m].components(separatedBy: CharacterSet(charactersIn: "0123456789.").inverted)
                .filter { !$0.isEmpty }.compactMap(Double.init)
            guard nums.count >= 3, nums[0...2].allSatisfy({ $0 <= 255 }) else { return nil }
            let a = nums.count > 3 ? nums[3] : 1
            return NSColor(srgbRed: nums[0] / 255, green: nums[1] / 255, blue: nums[2] / 255, alpha: a)
        }
        return nil
    }
}

// MARK: - Link previews

@MainActor
enum LinkVisuals {
    static func fetch(_ url: URL, done: @escaping @MainActor (Data?, Data?) -> Void) {
        let provider = LPMetadataProvider()
        provider.timeout = 15
        provider.startFetchingMetadata(for: url) { meta, _ in
            guard let meta else { return }
            let group = DispatchGroup()
            var icon: Data?
            var preview: Data?
            if let p = meta.iconProvider {
                group.enter()
                p.loadDataRepresentation(forTypeIdentifier: UTType.image.identifier) { d, _ in
                    icon = d.flatMap { downscaled($0, max: 64) }
                    group.leave()
                }
            }
            if let p = meta.imageProvider {
                group.enter()
                p.loadDataRepresentation(forTypeIdentifier: UTType.image.identifier) { d, _ in
                    preview = d.flatMap { downscaled($0, max: 800) }
                    group.leave()
                }
            }
            group.notify(queue: .main) {
                MainActor.assumeIsolated {
                    if icon != nil || preview != nil { done(icon, preview) }
                }
            }
        }
    }

    nonisolated static func downscaled(_ data: Data, max: Int) -> Data? {
        guard let src = CGImageSourceCreateWithData(data as CFData, nil) else { return nil }
        let opts: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: max,
        ]
        guard let cg = CGImageSourceCreateThumbnailAtIndex(src, 0, opts as CFDictionary) else { return nil }
        return NSBitmapImageRep(cgImage: cg).representation(using: .png, properties: [:])
    }
}
